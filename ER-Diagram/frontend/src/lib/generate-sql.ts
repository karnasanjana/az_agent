// Generate DDL SQL from the current schema

import type { DatabaseSchema, Table, ForeignKey } from '@/types/schema'
import type { ManualRelationship } from '@/types/diagram'

/**
 * Generate complete DDL SQL for the schema.
 * Detects BigQuery vs SQL Server from db_type in sessionStorage.
 */
export function generateDDL(
  schema: DatabaseSchema,
  manualRelationships: ManualRelationship[] = [],
): string {
  const dbType = typeof window !== 'undefined'
    ? sessionStorage.getItem('db_type') || 'bigquery'
    : 'bigquery'

  const lines: string[] = []

  // Header comment
  lines.push(`-- Schema DDL generated by DataLake Orchestrator`)
  lines.push(`-- Database: ${schema.database_name}`)
  lines.push(`-- Tables: ${schema.table_count}, Relationships: ${schema.foreign_keys.length + manualRelationships.length}`)
  lines.push(`-- Generated: ${new Date().toISOString()}`)
  lines.push('')

  if (dbType === 'bigquery') {
    lines.push(...generateBigQueryDDL(schema, manualRelationships))
  } else {
    lines.push(...generateSqlServerDDL(schema, manualRelationships))
  }

  return lines.join('\n')
}

function generateBigQueryDDL(
  schema: DatabaseSchema,
  manualRelationships: ManualRelationship[],
): string[] {
  const lines: string[] = []

  // Group tables by dataset
  const datasets = new Map<string, Table[]>()
  for (const table of schema.tables) {
    const ds = table.schema_name
    if (!datasets.has(ds)) datasets.set(ds, [])
    datasets.get(ds)!.push(table)
  }

  for (const [dataset, tables] of datasets) {
    lines.push(`-- ========================================`)
    lines.push(`-- Dataset: ${dataset}`)
    lines.push(`-- ========================================`)
    lines.push('')

    for (const table of tables) {
      const qualifier = `\`${schema.database_name}.${dataset}.${table.table_name}\``

      if (table.is_view) {
        lines.push(`-- VIEW: ${qualifier}`)
        lines.push(`-- (View definition not available from schema extraction)`)
      } else {
        lines.push(`CREATE TABLE ${qualifier} (`)

        const colLines: string[] = []
        for (const col of table.columns) {
          const bqType = mapToBigQueryType(col.data_type)
          const nullable = col.is_nullable ? '' : ' NOT NULL'
          colLines.push(`  ${col.name} ${bqType}${nullable}`)
        }
        lines.push(colLines.join(',\n'))
        lines.push(`);`)
      }
      lines.push('')
    }
  }

  // Foreign key constraints
  const allFks = [...schema.foreign_keys]

  // Add manual relationships as FK constraints
  for (const rel of manualRelationships) {
    allFks.push({
      constraint_name: rel.id,
      source_table: rel.source_table,
      source_schema: rel.source_database,
      source_columns: [rel.source_column],
      target_table: rel.target_table,
      target_schema: rel.target_database,
      target_columns: [rel.target_column],
    })
  }

  if (allFks.length > 0) {
    lines.push(`-- ========================================`)
    lines.push(`-- Relationships`)
    lines.push(`-- ========================================`)
    lines.push('')

    for (const fk of allFks) {
      const srcTable = `\`${schema.database_name}.${fk.source_schema}.${fk.source_table}\``
      const tgtTable = `\`${schema.database_name}.${fk.target_schema}.${fk.target_table}\``
      const srcCols = fk.source_columns.join(', ')
      const tgtCols = fk.target_columns.join(', ')

      lines.push(`ALTER TABLE ${srcTable}`)
      lines.push(`  ADD CONSTRAINT ${fk.constraint_name}`)
      lines.push(`  FOREIGN KEY (${srcCols})`)
      lines.push(`  REFERENCES ${tgtTable}(${tgtCols});`)
      lines.push('')
    }
  }

  return lines
}

function generateSqlServerDDL(
  schema: DatabaseSchema,
  manualRelationships: ManualRelationship[],
): string[] {
  const lines: string[] = []

  // Group tables by schema
  const schemas = new Map<string, Table[]>()
  for (const table of schema.tables) {
    const s = table.schema_name
    if (!schemas.has(s)) schemas.set(s, [])
    schemas.get(s)!.push(table)
  }

  for (const [schemaName, tables] of schemas) {
    lines.push(`-- ========================================`)
    lines.push(`-- Schema: ${schemaName}`)
    lines.push(`-- ========================================`)
    lines.push('')

    for (const table of tables) {
      const qualifier = `[${schemaName}].[${table.table_name}]`

      if (table.is_view) {
        lines.push(`-- VIEW: ${qualifier}`)
        lines.push(`-- (View definition not available from schema extraction)`)
      } else {
        lines.push(`CREATE TABLE ${qualifier} (`)

        const colLines: string[] = []
        const pkCols: string[] = []

        for (const col of table.columns) {
          const tsqlType = mapToSqlServerType(col.data_type)
          const nullable = col.is_nullable ? 'NULL' : 'NOT NULL'
          const identity = col.is_identity ? ' IDENTITY(1,1)' : ''
          colLines.push(`  [${col.name}] ${tsqlType}${identity} ${nullable}`)

          if (col.is_primary_key) {
            pkCols.push(`[${col.name}]`)
          }
        }

        if (pkCols.length > 0) {
          colLines.push(`  CONSTRAINT PK_${table.table_name} PRIMARY KEY (${pkCols.join(', ')})`)
        }

        lines.push(colLines.join(',\n'))
        lines.push(`);`)
        lines.push(`GO`)
      }
      lines.push('')
    }
  }

  // Foreign key constraints
  const allFks = [...schema.foreign_keys]

  for (const rel of manualRelationships) {
    allFks.push({
      constraint_name: rel.id,
      source_table: rel.source_table,
      source_schema: rel.source_database,
      source_columns: [rel.source_column],
      target_table: rel.target_table,
      target_schema: rel.target_database,
      target_columns: [rel.target_column],
    })
  }

  if (allFks.length > 0) {
    lines.push(`-- ========================================`)
    lines.push(`-- Foreign Key Constraints`)
    lines.push(`-- ========================================`)
    lines.push('')

    for (const fk of allFks) {
      const srcTable = `[${fk.source_schema}].[${fk.source_table}]`
      const tgtTable = `[${fk.target_schema}].[${fk.target_table}]`
      const srcCols = fk.source_columns.map(c => `[${c}]`).join(', ')
      const tgtCols = fk.target_columns.map(c => `[${c}]`).join(', ')

      lines.push(`ALTER TABLE ${srcTable}`)
      lines.push(`  ADD CONSTRAINT [${fk.constraint_name}]`)
      lines.push(`  FOREIGN KEY (${srcCols})`)
      lines.push(`  REFERENCES ${tgtTable}(${tgtCols});`)
      lines.push(`GO`)
      lines.push('')
    }
  }

  return lines
}

function mapToBigQueryType(dataType: string): string {
  const t = dataType.toLowerCase()
  const mapping: Record<string, string> = {
    'int': 'INT64', 'integer': 'INT64', 'bigint': 'INT64', 'smallint': 'INT64', 'tinyint': 'INT64',
    'float': 'FLOAT64', 'real': 'FLOAT64', 'double': 'FLOAT64', 'decimal': 'NUMERIC', 'numeric': 'NUMERIC',
    'money': 'NUMERIC', 'smallmoney': 'NUMERIC',
    'varchar': 'STRING', 'nvarchar': 'STRING', 'char': 'STRING', 'nchar': 'STRING',
    'text': 'STRING', 'ntext': 'STRING', 'string': 'STRING',
    'bit': 'BOOL', 'boolean': 'BOOL', 'bool': 'BOOL',
    'date': 'DATE', 'datetime': 'DATETIME', 'datetime2': 'DATETIME', 'timestamp': 'TIMESTAMP',
    'time': 'TIME', 'datetimeoffset': 'TIMESTAMP',
    'uniqueidentifier': 'STRING', 'xml': 'STRING',
    'binary': 'BYTES', 'varbinary': 'BYTES', 'image': 'BYTES',
  }
  return mapping[t] || t.toUpperCase()
}

function mapToSqlServerType(dataType: string): string {
  const t = dataType.toLowerCase()
  // Most types from schema extraction are already SQL Server types
  const mapping: Record<string, string> = {
    'string': 'NVARCHAR(MAX)', 'bool': 'BIT', 'boolean': 'BIT',
    'int64': 'BIGINT', 'float64': 'FLOAT', 'numeric': 'DECIMAL(18,2)',
    'bytes': 'VARBINARY(MAX)',
  }
  return mapping[t] || t.toUpperCase()
}
